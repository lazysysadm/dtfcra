export const mission = pgTable(
  "mission",
  {
    id: uuid("id")
      .primaryKey()
      .default(sql`uuidv7()`),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    clientId: uuid("client_id")
      .notNull()
      .references(() => client.id, { onDelete: "restrict" }),
    title: text("title").notNull(),
    startDate: date("start_date").notNull(),
    endDate: date("end_date"),
    tjmCents: integer("tjm_cents").notNull().default(0),
    unit: text("unit", { enum: ["day", "hour"] })
      .notNull()
      .default("day"),
    hoursPerDay: numeric("hours_per_day", { precision: 4, scale: 2 }).notNull().default("7"),
    holidayTerritory: text("holiday_territory", { enum: TERRITORIES })
      .notNull()
      .default("metropole"),
    exportTemplateId: uuid("export_template_id").references(() => exportTemplate.id, {
      onDelete: "set null",
    }),
    status: text("status", { enum: ["active", "archived"] })
      .notNull()
      .default("active"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    index("mission_user_id_idx").on(table.userId),
    index("mission_client_id_idx").on(table.clientId),
    check("mission_unit_check", sql`${table.unit} in ('day', 'hour')`),
    check("mission_status_check", sql`${table.status} in ('active', 'archived')`),
    check("mission_territory_check", territoryCheck(table.holidayTerritory)),
  ],
);

// One CRA = one mission × one month. Saved directly, editable at any time
// (no submission workflow, no versioning).
export const timesheet = pgTable(
  "timesheet",
  {
    id: uuid("id")
      .primaryKey()
      .default(sql`uuidv7()`),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    missionId: uuid("mission_id")
      .notNull()
      .references(() => mission.id, { onDelete: "restrict" }),
    year: integer("year").notNull(),
    month: integer("month").notNull(),
    globalComment: text("global_comment"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    uniqueIndex("timesheet_mission_period_idx").on(table.missionId, table.year, table.month),
    index("timesheet_user_id_idx").on(table.userId),
    index("timesheet_mission_id_idx").on(table.missionId),
    check("timesheet_month_check", sql`${table.month} between 1 and 12`),
    check("timesheet_year_check", sql`${table.year} between 2000 and 2100`),
  ],
);

export const timesheetEntry = pgTable(
  "timesheet_entry",
  {
    id: uuid("id")
      .primaryKey()
      .default(sql`uuidv7()`),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    timesheetId: uuid("timesheet_id")
      .notNull()
      .references(() => timesheet.id, { onDelete: "cascade" }),
    date: date("date").notNull(),
    quantity: numeric("quantity", { precision: 4, scale: 2 }).notNull(),
    type: text("type", {
      enum: ["worked", "remote", "onsite", "on_call", "leave", "unavailable"],
    })
      .notNull()
      .default("worked"),
    comment: text("comment"),
  },
  (table) => [
    uniqueIndex("timesheet_entry_timesheet_date_idx").on(table.timesheetId, table.date),
    index("timesheet_entry_timesheet_id_idx").on(table.timesheetId),
    index("timesheet_entry_user_date_idx").on(table.userId, table.date),
    check(
      "timesheet_entry_type_check",
      sql`${table.type} in ('worked', 'remote', 'onsite', 'on_call', 'leave', 'unavailable')`,
    ),
    check(
      "timesheet_entry_quantity_check",
      sql`${table.quantity} >= 0 and ${table.quantity} <= 24`,
    ),
  ],
);
