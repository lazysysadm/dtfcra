import { sql, type Column } from "drizzle-orm";
import {
  check,
  date,
  index,
  integer,
  jsonb,
  numeric,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { user } from "./auth-schema";
import { TERRITORIES } from "@/lib/holidays/territories";

const territoryCheck = (column: Column) =>
  // Literal values (not bound parameters): CHECK constraints cannot use $n.
  sql`${column} in (${sql.raw(TERRITORIES.map((territory) => `'${territory}'`).join(", "))})`;

// Better Auth tables (user, session, account, verification, twoFactor,
// passkey, rateLimit) — generated by `pnpm auth:generate`, do not edit.
export * from "./auth-schema";

// Append-only audit trail (no update/delete path is exposed anywhere).
// userId is text (matches Better Auth user.id) with FK set null on account
// deletion: audit rows are retained for legal traceability (see SECURITY.md).
export const auditLog = pgTable(
  "audit_log",
  {
    id: uuid("id")
      .primaryKey()
      .default(sql`uuidv7()`),
    userId: text("user_id").references(() => user.id, { onDelete: "set null" }),
    actor: text("actor", { enum: ["user", "system"] }).notNull(),
    action: text("action").notNull(),
    entity: text("entity"),
    entityId: uuid("entity_id"),
    metadata: jsonb("metadata"),
    ip: text("ip"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [index("audit_log_user_created_idx").on(table.userId, table.createdAt)],
);

// Fixed-window rate limiter (per-user counters for costly endpoints).
export const publicRateLimit = pgTable("public_rate_limit", {
  key: text("key").primaryKey(),
  count: integer("count").notNull().default(0),
  windowStart: timestamp("window_start", { withTimezone: true }).notNull().defaultNow(),
});

// Progressive sign-in lockout per account (exponential backoff after 5 failures).
export const loginLockout = pgTable("login_lockout", {
  key: text("key").primaryKey(),
  failures: integer("failures").notNull().default(0),
  lockedUntil: timestamp("locked_until", { withTimezone: true }),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

// One freelancer profile per user (raison sociale, SIRET, TVA, marque).
export const freelancerProfile = pgTable(
  "freelancer_profile",
  {
    id: uuid("id")
      .primaryKey()
      .default(sql`uuidv7()`),
    userId: text("user_id")
      .notNull()
      .unique()
      .references(() => user.id, { onDelete: "cascade" }),
    legalName: text("legal_name").notNull(),
    consultantName: text("consultant_name"),
    legalForm: text("legal_form"),
    siret: text("siret"),
    address: text("address"),
    vatNumber: text("vat_number"),
    logoPath: text("logo_path"),
    brandColor: text("brand_color").notNull().default("#0f172a"),
    holidayTerritory: text("holiday_territory", { enum: TERRITORIES })
      .notNull()
      .default("metropole"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [check("profile_territory_check", territoryCheck(table.holidayTerritory))],
);

